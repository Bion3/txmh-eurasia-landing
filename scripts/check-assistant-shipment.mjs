import assert from 'node:assert/strict';
import {extractShipment,shipmentQuoteHref} from '../src/lib/assistantShipment.js';
const a=extractShipment('上海到汉堡 拼箱 8cbm 5000kg');
assert.equal(a.pol,'上海');assert.equal(a.pod,'汉堡');assert.equal(a.containerType,'LCL');assert.equal(a.weight,5000);
const b=extractShipment('改成 2.5 吨',a);assert.equal(b.weight,2500);assert.equal(b.volume,8);assert.equal(b.pod,'汉堡');
const c=extractShipment('Ningbo to Duisburg FCL 40HQ 2 containers');assert.equal(c.quantity,2);assert.equal(c.containerSize,'40HQ');
assert.equal(extractShipment('door to door',c).serviceScope,'door_to_door');
assert.equal(extractShipment('DDP',a).serviceScope,'ddp');
assert.equal(extractShipment('-5kg',a).weight,-5);
const url=new URL(shipmentQuoteHref(b,'test handoff'),'https://www.eurasiago.com');assert.equal(url.searchParams.get('weight'),'2500');assert.equal(url.searchParams.get('notes'),'test handoff');
const screenshot=extractShipment('上海 杜堡，拼箱10方 4吨');
assert.equal(screenshot.pol,'上海');assert.equal(screenshot.pod,'杜伊斯堡');
assert.equal(screenshot.containerType,'LCL');assert.equal(screenshot.volume,10);assert.equal(screenshot.weight,4000);
const followup=extractShipment('杜堡',extractShipment('上海，拼箱10方4吨'));
assert.equal(followup.pod,'杜伊斯堡');assert.equal(followup.weight,4000);assert.equal(followup.volume,10);
assert.equal(extractShipment('布达').pod,'布达佩斯');assert.equal(extractShipment('叶卡').pod,'叶卡捷琳堡');
const screenshotUrl=new URL(shipmentQuoteHref(screenshot),'https://www.eurasiago.com');
assert.equal(screenshotUrl.searchParams.get('pod'),'杜伊斯堡');assert.equal(screenshotUrl.searchParams.get('weight'),'4000');
console.log('Assistant extraction and handoff checks passed, including Duisburg shorthand and compact Chinese cargo input.');
// Regression: cargo units without "LCL" must not inherit a default FCL lookup.
const implicit=extractShipment('上海 汉堡 3方6吨');
assert.equal(implicit.containerType,'LCL');assert.equal(implicit.volume,3);assert.equal(implicit.weight,6000);
const legacyDefault=extractShipment('上海 汉堡 3方6吨',{containerType:'FCL',serviceScope:'door'});
assert.equal(legacyDefault.containerType,'LCL');assert.equal(legacyDefault.serviceScope,'door_to_station');
const chosenFcl=extractShipment('整柜40HQ');
assert.equal(extractShipment('上海 汉堡3方6吨',chosenFcl).containerType,'FCL');
assert.equal(extractShipment('改成拼箱3方6吨',chosenFcl).containerSize,undefined);
console.log('Implicit LCL cargo requests and explicit FCL choices remain distinct.');
