const api=new Function('publicSupabase','withRequestDeadline','success','fetch',source+'\nreturn leadsApi;')(client,withRequestDeadline,data=>({data}),async()=>{calls++;return Response.json({status:'sent'});});
const payload={source_type:'website_form',contact_name:'Test',origin:'上海',destination:'汉堡',website_visit:{session_id:'test'}};
const first=await api.createPublic(payload);
assert.equal(first.data.notificationStatus,'sent');
assert.equal(first.data.id,inserted[0].id);
assert.equal(inserted[0].website_visit,undefined);
error={code:'23505',message:'duplicate key value violates unique constraint "leads_pkey"'};
await api.createPublic(payload);
assert.equal(inserted[0].id,inserted[1].id);
error={code:'42501',message:'denied'};
